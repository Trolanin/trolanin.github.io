"""Flatten poe.ninja exchange prices (data/prices/<league>/*.json) into build/prices.txt.

Usage:  python prices.py [--league NAME] [--out build/prices.txt]
Output: one line per item, '<name>\\t<price in chaos>', sorted by name; '#' lines are comments.
The league defaults to the one recorded in data/manifest.json (else the newest price folder).
Prices poe.ninja does not carry (beasts, ...) are set in mechanics.cfg as 'price.<name> = x'.
Standard library only.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--league")
    ap.add_argument("--out", default=str(ROOT / "build" / "prices.txt"))
    a = ap.parse_args()
    league = a.league
    if not league:
        man = ROOT / "data" / "manifest.json"
        if man.exists():
            league = json.loads(man.read_text(encoding="utf-8")).get("league")
    pdir = ROOT / "data" / "prices"
    if not league or not (pdir / league).is_dir():
        dirs = sorted((d for d in pdir.iterdir() if d.is_dir()), key=lambda d: d.stat().st_mtime)
        if not dirs:
            raise SystemExit("no price data; run fetch_data.py first")
        league = dirs[-1].name
    prices: dict[str, float] = {}
    for f in sorted((pdir / league).glob("*.json")):
        doc = json.loads(f.read_text(encoding="utf-8"))
        names = {i["id"]: i["name"] for i in doc.get("items", [])}
        primary = (doc.get("core") or {}).get("primary", "chaos")
        if primary != "chaos":
            raise SystemExit(f"{f}: primary currency is {primary!r}, expected chaos")
        for line in doc.get("lines", []):
            n, v = names.get(line.get("id")), line.get("primaryValue")
            if n and isinstance(v, (int, float)) and v > 0:
                prices[n] = float(v)
    prices.setdefault("Chaos Orb", 1.0)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fo:
        fo.write(f"# poe.ninja prices in chaos, league {league}; generated by prices.py\n")
        for n in sorted(prices):
            fo.write(f"{n}\t{prices[n]:.6g}\n")
    print(f"{out}: {len(prices)} prices ({league})")


if __name__ == "__main__":
    main()
